#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

function readPackage() {
  return JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
}

function getReleaseMetadata(pkg = readPackage()) {
  const release = pkg.foxbearRelease || {};
  const productVersion = String(pkg.version || '').trim();
  const buildId = String(release.buildId || '').trim();
  const assetVersion = String(release.assetVersion || `${productVersion}-${buildId}`).trim();
  const cacheName = String(release.cacheName || `foxbear-shell-v${assetVersion}`).trim();
  const bootRevision = String(release.bootRevision || '').trim();
  const updateSafetyRevision = String(release.updateSafetyRevision || '').trim();
  const serviceWorkerRevision = String(release.serviceWorkerRevision || '').trim();

  const values = { productVersion, buildId, assetVersion, cacheName, bootRevision, updateSafetyRevision, serviceWorkerRevision };
  Object.entries(values).forEach(([key, value]) => {
    if (!value) throw new Error(`package.json foxbearRelease.${key} is required`);
  });
  if (!/^\d+\.\d+\.\d+$/.test(productVersion)) {
    throw new Error(`package.json version must be semantic x.y.z, received: ${productVersion}`);
  }
  if (!/^[a-z0-9][a-z0-9-]*$/.test(buildId)) {
    throw new Error(`buildId must be lowercase kebab-case, received: ${buildId}`);
  }
  if (cacheName !== `foxbear-shell-v${assetVersion}`) {
    throw new Error(`cacheName must equal foxbear-shell-v${assetVersion}`);
  }

  return Object.freeze({
    ...values,
    appVersion: `Pro v${productVersion}`
  });
}

function renderBuildInfo(meta = getReleaseMetadata()) {
  return `// Generated by tools/sync-release-metadata.js from package.json.\n'use strict';\n\n(function exposeFoxBearBuildInfo(global) {\n  const info = Object.freeze({\n    productVersion: '${meta.productVersion}',\n    appVersion: '${meta.appVersion}',\n    buildId: '${meta.buildId}',\n    assetVersion: '${meta.assetVersion}',\n    cacheName: '${meta.cacheName}',\n    bootRevision: '${meta.bootRevision}',\n    updateSafetyRevision: '${meta.updateSafetyRevision}',\n    serviceWorkerRevision: '${meta.serviceWorkerRevision}'\n  });\n  global.FoxBearBuildInfo = info;\n})(typeof window !== 'undefined' ? window : globalThis);\n`;
}

module.exports = { ROOT, readPackage, getReleaseMetadata, renderBuildInfo };
